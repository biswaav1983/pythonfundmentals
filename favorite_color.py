print("🎨 Color Personality Quiz")

color = input("What's your favorite color? ").lower()

if color == "red":
    print("❤️ Red lovers are passionate and energetic!")
elif color == "blue":
    print("💙 Blue lovers are calm and trustworthy!")
elif color == "green":
    print("💚 Green lovers are balanced and peaceful!")
elif color == "yellow":
    print("💛 Yellow lovers are optimistic and creative!")
elif color == "purple":
    print("💜 Purple lovers are mysterious and unique!")
else:
    print("🌈 Great choice! Every color has its own beauty!")

print(f"\n✨ {color.title()} is a wonderful color!")
