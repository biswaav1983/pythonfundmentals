print("🌤️ Weather Decision Maker")

temperature = float(input("What's the temperature today? "))

if temperature >= 20:
    print("🌞 It's warm! Perfect for outdoor activities!")
    print("   Maybe go for a walk or have a picnic!")
else:
    print("🧥 It's cool! You might want a jacket!")
    print("   Great weather for hot chocolate!")

print("\n🎯 Enjoy your day!")
