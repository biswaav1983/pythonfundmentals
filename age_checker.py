print("🎂 Age Category Checker")

age = int(input("How old are you? "))

if age >= 18:
    print("🧑 You are an adult!")
    print("   You can vote, drive, and make important decisions.")
else:
    print("👶 You are still young!")
    print("   Enjoy this time of learning and growing!")

print(f"\n💫 At {age} years old, you have many adventures ahead!")
